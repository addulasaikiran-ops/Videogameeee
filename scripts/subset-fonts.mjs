// npm run fonts — downloads the two Google Fonts families used by the game,
// subsets them to the glyphs we actually need, and writes self-hosted
// .woff2 files + a generated fonts.css into public/fonts/.
// Requires: python with `pip install fonttools brotli` on PATH.
// Run manually when the type system changes; the output is committed.
import { execFileSync } from 'node:child_process';
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outDir = join(root, 'public', 'fonts');
mkdirSync(outDir, { recursive: true });

const UA = 'Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120 Safari/537.36';
const QUERY =
  'https://fonts.googleapis.com/css2?family=Cormorant+Garamond:ital,wght@0,500;0,600;0,700;1,500;1,600&family=Jost:ital,wght@0,300;0,400;0,500;0,600;1,400&family=Marcellus&display=swap';

// Glyphs worth keeping: latin, punctuation, digits, arrows/glyphs used in UI text.
const SUBSET = '--unicodes=U+0000-00FF,U+2000-206F,U+2190-21FF,U+25A0-25FF,U+2660-27BF,U+FE00-FE0F';

const css = await (await fetch(QUERY, { headers: { 'User-Agent': UA } })).text();
const blocks = [...css.matchAll(/@font-face\s*{([^}]+)}/g)];
if (!blocks.length) { console.error('no @font-face blocks returned'); process.exit(1); }

let outCss = `/* generated by scripts/subset-fonts.mjs — do not edit by hand */\n`;
let count = 0, totalKb = 0, idx = 0;
for (const b of blocks) {
  const body = b[1];
  const family = body.match(/font-family:\s*'([^']+)'/)[1];
  const fileBase = family.replace(/\s+/g, '');
  const style = (body.match(/font-style:\s*(\w+)/) || [])[1] || 'normal';
  const weight = (body.match(/font-weight:\s*(\d+)/) || [])[1] || '400';
  const range = (body.match(/unicode-range:\s*([^;]+)/) || [])[1];
  const url = (body.match(/url\((https:[^)]+)\)/) || [])[1];
  if (!url) continue;

  const tmp = join(outDir, 'tmp.ttf');
  const buf = Buffer.from(await (await fetch(url)).arrayBuffer());
  writeFileSync(tmp, buf);

  // google splits each face into unicode-range slices — give each its own file
  const name = `${fileBase}-${weight}${style === 'italic' ? 'i' : ''}.${idx++}.woff2`;
  execFileSync('pyftsubset', [tmp, `--output-file=${join(outDir, name)}`, '--flavor=woff2',
    SUBSET, '--layout-features=*', '--no-hinting', '--desubroutinize'], { stdio: 'pipe' });
  const { size } = (await import('node:fs')).statSync(join(outDir, name));
  totalKb += size / 1024;
  outCss += `@font-face{font-family:'${family}';font-style:${style};font-weight:${weight};font-display:swap;src:url(./${name}) format('woff2');${range ? `unicode-range:${range.trim()};` : ''}}\n`;
  count++;
}
writeFileSync(join(outDir, 'fonts.css'), outCss);
try { (await import('node:fs')).unlinkSync(join(outDir, 'tmp.ttf')); } catch {}
console.log(`subset-fonts: wrote ${count} faces, ${totalKb.toFixed(0)} kB total → public/fonts/`);
